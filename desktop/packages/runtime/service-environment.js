function selectKeys(source, allowedKeys) {
  const allowed = new Set([...OS_ENV_KEYS, ...allowedKeys].map((key) => key.toUpperCase()));
  const selected = new Map();
  for (const [key, value] of Object.entries(source || {})) {
    const normalized = key.toUpperCase();
    if (value === undefined || !allowed.has(normalized)) continue;
    selected.set(normalized, [key, value]);
  }
  return Object.fromEntries(selected.values());
}

function selectServiceEnvironment(serviceName, baseEnv = process.env, overrides = {}) {
  const keys = SERVICE_KEYS[serviceName];
  if (!keys) throw new Error(`Unknown runtime service: ${serviceName}`);
  return selectKeys({ ...baseEnv, ...overrides }, keys);
}

function selectWrapperEnvironment(serviceName, env) {
  if (!SERVICE_KEYS[serviceName]) throw new Error(`Unknown runtime service: ${serviceName}`);
  const selected = new Map();
  for (const [key, value] of Object.entries(env || {})) {
    const normalized = key.toUpperCase();
    if (value === undefined || !WRAPPER_KEYS.has(normalized)) continue;
    selected.set(normalized, [key, value]);
  }
  return Object.fromEntries(selected.values());
}

function renderWindowsWrapperEnvironment(serviceName, env) {
  return Object.entries(selectWrapperEnvironment(serviceName, env)).map(([key, value]) =>
    `set "${String(key).replace(/"/g, "")}=${String(value ?? "").replace(/\r?\n/g, " ").replace(/"/g, '""')}"`,
  );
}

